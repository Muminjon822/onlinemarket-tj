export function placeholder(category) {
  const icon = categoryById(category).icon;
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 200 200"><rect width="200" height="200" fill="#e8f3ee"/><text x="100" y="125" font-size="80" text-anchor="middle">${icon}</text></svg>`;
  return `data:image/svg+xml;utf8,${encodeURIComponent(svg)}`;
}

/** Допускаются только фото, сохранённые у нас (data:image) и https-ссылки. */
export function productImage(p, i = 0) {
  const src = (p.images || [])[i];
  return src && /^(data:image\/|https:\/\/)/.test(src) ? src : placeholder(p.category);
}

